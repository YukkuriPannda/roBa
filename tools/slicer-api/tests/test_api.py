def test_worker_loop_survives_run_exception(tmp_path):
    """Even if run() itself raises, the worker keeps processing the queue."""
    store = JobStore(tmp_path / "jobs")
    store.save(_record("x1", "queued", "2026-01-01T00:00:00+00:00"))
    store.save(_record("x2", "queued", "2026-01-01T00:00:01+00:00"))
    service = JobService(store, FakeOrca())
    seen: list[str] = []

    async def fake_run(job_id: str) -> None:
        seen.append(job_id)
        if job_id == "x1":
            raise RuntimeError("run exploded")
        store.get(job_id)["status"] = "succeeded"

    service.run = fake_run  # type: ignore[assignment]

    async def scenario():
        worker = asyncio.create_task(service._worker())
        service.queue.put_nowait("x1")
        service.queue.put_nowait("x2")
        await service.queue.join()
        worker.cancel()
        try:
            await worker
        except asyncio.CancelledError:
            pass

    asyncio.run(scenario())
    assert seen == ["x1", "x2"]
    assert store.get("x1")["status"] == "failed"


def test_retention_removes_old_finished_jobs(tmp_path):
    from datetime import datetime, timedelta, timezone

    store = JobStore(tmp_path / "jobs")
    old = (datetime.now(timezone.utc) - timedelta(hours=30)).isoformat()
    new = (datetime.now(timezone.utc) - timedelta(hours=1)).isoformat()
    store.save(_record("old", "succeeded", old, old))
    store.save(_record("new", "succeeded", new, new))
    service = JobService(store, FakeOrca(), retention_hours=24)
    assert service.cleanup_expired() == ["old"]
    assert store.get("old") is None
    assert not (tmp_path / "jobs" / "old").exists()
    assert store.get("new") is not None


def test_cleanup_sweeps_orphan_dirs_and_survives_bad_records(tmp_path):
    store = JobStore(tmp_path / "jobs")
    orphan = store.job_dir("orphan")
    orphan.mkdir(parents=True)
    old = time.time() - 7200
    os.utime(orphan, (old, old))
    fresh = store.job_dir("fresh-orphan")
    fresh.mkdir(parents=True)
    broken = store.job_dir("broken")
    broken.mkdir(parents=True)
    (broken / "job.json").write_text("{not json", encoding="utf-8")
    service = JobService(store, FakeOrca())
    assert service.cleanup_expired() == ["orphan"]
    assert fresh.exists() and broken.exists()
