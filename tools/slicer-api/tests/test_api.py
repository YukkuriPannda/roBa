def _wait(client: TestClient, job_id: str, states=("succeeded", "failed"), timeout=10.0) -> dict:
    deadline = time.time() + timeout
    while time.time() < deadline:
        job = client.get(f"/jobs/{job_id}").json()
        if job["status"] in states:
            return job
        time.sleep(0.05)
    raise AssertionError(f"job did not reach {states}: {job}")


def _post(client, data=b"solid x\nendsolid x\n", name="part.stl", printer="ad4",
          mime="model/stl", **extra):
    files = {"file": (name, data, mime)}
    for field in ("machine_profile", "process_profile", "filament_profile"):
        if field in extra:
            files[field] = extra.pop(field)
    return client.post("/jobs", data={"printer": printer, **extra}, files=files)


def _record(job_id: str, status: str, created: str, finished: str | None = None) -> dict:
    return {"job_id": job_id, "status": status, "printer": "ad4", "outputs": ["gcode"],
            "input": {"name": "m.stl", "original_name": "m.stl", "size": 1},
            "profile_overrides": [], "created_at": created, "finished_at": finished,
            "error": None, "files": [], "validation": {}, "metadata": {}}


