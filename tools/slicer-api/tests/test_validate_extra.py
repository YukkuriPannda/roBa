"""Validator and GX tests added with the review fixes."""

from __future__ import annotations

import io

import pytest
from PIL import Image

from app.gx import read_gx, write_gx
from app.validate import Bounds, ValidationError, validate_gcode, validate_gx

AD4_BOUNDS = Bounds(x_min=-110.0, x_max=110.0, y_min=-100.0, y_max=100.0, z_max=250.0)
GCODE = b";generated by ffslicer\nG90\nG1 X0 Y0 Z0.2 F3000\nG1 X10 Y0 E1.0\n"


def _gc(*lines: str) -> bytes:
    return ("\n".join(lines) + "\n").encode()


def test_case_insensitive_with_line_numbers_and_g00():
    gc = _gc("n10 g00 x-10 y-10", "N11 G01 X10 Y10 e1", "n12 g1 x-10 y10 E2")
    assert validate_gcode(gc, AD4_BOUNDS)["g1_moves"] == 2


def test_dot_number_formats_accepted():
    gc = _gc("G1 X.5 Y-.5 E1.", "G1 X10. Y-10.")
    assert validate_gcode(gc, AD4_BOUNDS)["g1_moves"] == 2


def test_relative_z_is_tracked():
    gc = _gc("G90", "G1 Z240", "G91", "G1 Z20", "G90")  # 260 > 250
    with pytest.raises(ValidationError, match="Z=260"):
        validate_gcode(gc, AD4_BOUNDS)


def test_g92_resets_position():
    gc = _gc("G90", "G92 X200 Y0", "G1 X201 Y0 E1")
    with pytest.raises(ValidationError, match="X=201"):
        validate_gcode(gc, AD4_BOUNDS)


def test_g28_makes_position_unknown():
    gc = _gc("G28", "G91", "G1 X5 E1", "G90", "G1 X0 E2")
    assert validate_gcode(gc, AD4_BOUNDS)["g1_moves"] == 2


def test_arc_bounding_box_outside_fails_and_inside_passes():
    inside = _gc("G90", "G1 X0 Y0 F3000", "G2 X10 Y0 I5 J0 E1", "G1 X20 E2")
    assert validate_gcode(inside, AD4_BOUNDS)["g1_moves"] == 2  # G2 is not a G1
    outside = _gc("G90", "G1 X100 Y0 F3000", "G2 X100.01 Y0 I50 J0 E1")
    with pytest.raises(ValidationError, match="arc X extent"):
        validate_gcode(outside, AD4_BOUNDS)


def test_arc_without_ij_rejected_when_bounded():
    gc = _gc("G90", "G1 X0 Y0", "G2 X1 Y1 R5 E1")
    with pytest.raises(ValidationError, match="I/J"):
        validate_gcode(gc, AD4_BOUNDS)


def test_z_below_floor_rejected_even_without_bounds():
    gc = _gc("G90", "G1 X0 Y0 Z-2 F600", "G1 X1 Z0 E1")
    with pytest.raises(ValidationError, match="below"):
        validate_gcode(gc, None)


def test_gx_clamps_out_of_range_header_fields():
    parsed = read_gx(write_gx(GCODE, {"layer_height_microns": 10**6, "bed_temp": -5,
                                      "material_right": 999}))
    assert parsed["layer_height_microns"] == 65535
    assert parsed["bed_temp"] == 0
    assert parsed["material_right"] == 255


def test_validate_gx_rejects_wrong_bmp_size():
    buf = io.BytesIO()
    Image.new("RGB", (10, 10)).save(buf, format="BMP")
    with pytest.raises(ValidationError, match="bmp"):
        validate_gx(write_gx(GCODE, bmp=buf.getvalue()), GCODE)


def test_validate_gx_accepts_default_output():
    info = validate_gx(write_gx(GCODE), GCODE)
    assert info["offset_bmp"] == 58
