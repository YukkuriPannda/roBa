def test_orca_client_sends_model_and_profiles_with_upstream_mime_types():
    import asyncio

    import httpx

    from app.orca_client import OrcaClient

    seen = {}

    def handler(request: httpx.Request) -> httpx.Response:
        seen["body"] = request.read()
        seen["ctype"] = request.headers["content-type"]
        return httpx.Response(200, content=b";gcode", headers={
            "content-disposition": 'attachment; filename="part.gcode"',
            "X-Print-Time-Seconds": "12"})

    client = OrcaClient("http://orca:3000", transport=httpx.MockTransport(handler))
    out = asyncio.run(client.slice(model=b"solid", model_name="part.stl", machine=b"{}",
                                   process=b"{}", filament=b"{}", export_type="gcode"))
    assert out.data == b";gcode"
    assert out.filename == "part.gcode"
    assert out.headers["x-print-time-seconds"] == "12"
    body = seen["body"]
    assert b'filename="part.stl"' in body
    assert b"Content-Type: model/stl" in body
    assert b'name="printerProfile"' in body and b"Content-Type: application/json" in body
    assert b'name="resolveProfileInheritance"' in body and b"true" in body
    assert seen["ctype"].startswith("multipart/form-data")
