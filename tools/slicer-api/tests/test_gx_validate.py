"""GX format and output validation tests (no network, no orca)."""

from __future__ import annotations

import io
import zipfile
from pathlib import Path

import pytest

from app.gx import read_gx, write_gx
from app.orca_client import OrcaError
from app.validate import (Bounds, ValidationError, validate_3mf, validate_gcode,
                          validate_gx)

SAMPLE_GX = Path(r"D:\OtherProjects\roBa-case\case\v3\freecad\trackball_bearing"
                 r"\generated\print\fit_coupon_print.gx")

AD4_BOUNDS = Bounds(x_min=-110.0, x_max=110.0, y_min=-100.0, y_max=100.0, z_max=250.0)

GCODE = (
    b";generated by ffslicer\n"
    b"G90\n"
    b"G1 X-10 Y-10 Z0.2 F3000\n"
    b"G1 X10 Y-10 E1.0 F1500\n"
    b"G1 X10 Y10 E2.0\n"
    b"G1 X-10 Y10 E3.0\n"
    b"; total layer number: 1\n"
    b"; filament used [mm] = 3.00\n"
    b"; estimated printing time (normal mode) = 1m 5s\n"
)


@pytest.mark.skipif(not SAMPLE_GX.exists(), reason="sample .gx not present")
def test_read_real_flashprint_sample_offsets_and_gcode():
    data = SAMPLE_GX.read_bytes()
    parsed = read_gx(data)
    assert parsed["offset_bmp"] == 58
    assert parsed["offset_png"] == 14512
    assert parsed["offset_gcode"] == 22599
    assert parsed["gcode"].startswith(b";generated by ffslicer")
    assert parsed["bmp"].startswith(b"BM")
    assert parsed["png"].startswith(b"\x89PNG")


def test_write_then_read_roundtrip():
    gx = write_gx(GCODE, {"print_time_secs": 65, "filament_mm_right": 3,
                          "layer_height_microns": 200, "perimeter_shells": 3,
                          "bed_temp": 50, "extruder_temp_right": 210})
    parsed = read_gx(gx)
    assert parsed["offset_bmp"] == 58
    assert parsed["offset_png"] == 58 + len(parsed["bmp"])
    assert parsed["offset_gcode"] == parsed["offset_png"] + len(parsed["png"])
    assert parsed["gcode"] == GCODE
    assert parsed["print_time_secs"] == 65
    assert parsed["filament_mm_right"] == 3
    assert parsed["layer_height_microns"] == 200
    assert parsed["bed_temp"] == 50
    assert parsed["extruder_temp_right"] == 210
    assert parsed["print_flags"] == 1
    assert parsed["material_right"] == 1
    assert parsed["material_left"] == 255
    assert len(parsed["bmp"]) == 14454  # 54-byte header + 80x60x3 with row padding


def test_read_gx_rejects_bad_magic():
    gx = bytearray(write_gx(GCODE))
    gx[0:1] = b"Z"
    with pytest.raises(ValueError, match="magic"):
        read_gx(bytes(gx))


def test_validate_gx_detects_gcode_mismatch():
    gx = write_gx(GCODE)
    with pytest.raises(ValidationError, match="differs"):
        validate_gx(gx, GCODE + b"G1 X0\n")
    info = validate_gx(gx, GCODE)
    assert info["gcode_identical"] is True


def test_validate_gcode_passes_inside_bounds():
    info = validate_gcode(GCODE, AD4_BOUNDS)
    assert info["g1_moves"] == 4
    assert info["layers"] == 1
    assert info["print_time_secs"] == 65
    assert info["filament_mm"] == 3.0


def test_validate_gcode_fails_outside_bounds():
    bad = GCODE + b"G1 X150 Y0 E4.0\n"
    with pytest.raises(ValidationError, match="X=150"):
        validate_gcode(bad, AD4_BOUNDS)


def test_validate_gcode_fails_height_over_limit():
    bad = GCODE + b"G1 Z260 F600\n"
    with pytest.raises(ValidationError, match="Z=260"):
        validate_gcode(bad, AD4_BOUNDS)


def test_validate_gcode_relative_mode_is_tracked():
    rel = (b"G90\nG1 X100 Y0 F3000\nG91\nG1 X20 E1\nG90\n"  # 120 is outside +110
           b"G1 X0 E2\n")
    with pytest.raises(ValidationError, match="X=120"):
        validate_gcode(rel, AD4_BOUNDS)


def test_validate_gcode_rejects_empty_and_no_moves():
    with pytest.raises(ValidationError, match="empty"):
        validate_gcode(b"  \n", None)
    with pytest.raises(ValidationError, match="no G1"):
        validate_gcode(b"G28\nM104 S0\n", None)


def _zip(members: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, data in members.items():
            zf.writestr(name, data)
    return buf.getvalue()


def test_validate_3mf_accepts_plate_gcode():
    data = _zip({"3D/3dmodel.model": b"<model/>", "Metadata/plate_1.gcode": GCODE})
    info = validate_3mf(data)
    assert info["gcode_member"] == "Metadata/plate_1.gcode"


def test_validate_3mf_requires_model_and_gcode():
    with pytest.raises(ValidationError, match="3dmodel"):
        validate_3mf(_zip({"Metadata/plate_1.gcode": GCODE}))
    with pytest.raises(ValidationError, match="no .gcode"):
        validate_3mf(_zip({"3D/3dmodel.model": b"<model/>"}))
    with pytest.raises(ValidationError, match="not a valid zip"):
        validate_3mf(b"not a zip")


